import fs from 'node:fs';
import path from 'node:path';

import type { Plugin } from 'vite';

const RESOLVE_EXTENSIONS = ['', '.ts', '.tsx', '.vue', '.js', '.mts'];
const INDEX_FILES = ['index.ts', 'index.tsx', 'index.vue', 'index.js'];

/** bare import：非相对、非绝对、非虚拟、非 #/ */
function isBarePackageImport(source: string): boolean {
  return (
    !source.startsWith('\0') &&
    !source.startsWith('#/') &&
    !source.startsWith('.') &&
    !path.isAbsolute(source) &&
    !source.includes('?')
  );
}

/** 拆出 Vite/Vue 查询串（如 ?vue&type=script），避免拼进文件路径导致 existsSync 失败 */
function splitQuery(source: string): { id: string; query: string } {
  const q = source.indexOf('?');
  if (q < 0) {
    return { id: source, query: '' };
  }
  return { id: source.slice(0, q), query: source.slice(q) };
}

function resolveExistingFile(basePath: string): string | null {
  if (fs.existsSync(basePath)) {
    const stat = fs.statSync(basePath);
    if (stat.isFile()) {
      return basePath;
    }
    if (stat.isDirectory()) {
      for (const indexFile of INDEX_FILES) {
        const candidate = path.join(basePath, indexFile);
        if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) {
          return candidate;
        }
      }
    }
  }

  for (const ext of RESOLVE_EXTENSIONS) {
    const candidate = `${basePath}${ext}`;
    if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) {
      return candidate;
    }
  }

  return null;
}

/** run-web-ele.mjs 写入院点本地 env 时的标记；主线启动时据此识别并清除残留 */
export const OPENHIS_PROJECT_LOCAL_ENV_MARKER = 'auto-generated by openhis-project/run-web-ele.mjs';

/** 解析 OPENHIS_PROJECT / VITE_OPENHIS_PROJECT，支持带或不带 project- 前缀 */
export function resolveOpenHisProjectId(): string | undefined {
  const raw = (process.env.OPENHIS_PROJECT ?? process.env.VITE_OPENHIS_PROJECT ?? '').trim();
  if (!raw) {
    return undefined;
  }
  return raw.startsWith('project-') ? raw.slice('project-'.length) : raw;
}

function parseEnvFileContent(content: string): Record<string, string> {
  const env: Record<string, string> = {};
  for (const line of content.split(/\r?\n/u)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }
    const idx = trimmed.indexOf('=');
    if (idx < 1) {
      continue;
    }
    env[trimmed.slice(0, idx).trim()] = trimmed.slice(idx + 1).trim();
  }
  return env;
}

function detectViteModeFromArgv(): string {
  const argv = process.argv;
  const modeIndex = argv.indexOf('--mode');
  if (modeIndex >= 0 && argv[modeIndex + 1]) {
    return argv[modeIndex + 1]!;
  }
  if (argv.some((item) => item === 'build' || item.endsWith('build'))) {
    return 'production';
  }
  return 'development';
}

/**
 * 主线 Vite 启动时清除院点脚本残留的本地 env 文件（如 env.development.local）。
 * 这些文件会被 Vite / loadAndConvertEnv 自动加载，若不清除会导致
 * `dev` / `dev:local` 误显示院点品牌名（如「长春市朝阳区中医院」）。
 * 院点模式（已设置 OPENHIS_PROJECT）下不清理。
 * 注意：块注释内禁止出现星号紧挨斜杠的 glob 写法，否则会提前结束注释。
 */
export function purgeStaleOpenHisProjectLocalEnv(webEleDir: string): void {
  if (resolveOpenHisProjectId()) {
    return;
  }

  let entries: string[];
  try {
    entries = fs.readdirSync(webEleDir);
  } catch {
    return;
  }

  for (const name of entries) {
    // .env.local / .env.development.local / .env.production.local …
    if (name !== '.env.local' && !/^\.env\.[^.]+\.local$/u.test(name)) {
      continue;
    }
    const filePath = path.join(webEleDir, name);
    try {
      const content = fs.readFileSync(filePath, 'utf8');
      if (!content.includes(OPENHIS_PROJECT_LOCAL_ENV_MARKER)) {
        continue;
      }
      fs.unlinkSync(filePath);
      console.log(`[openhis-project] purged stale ${name} (mainline start)`);
    } catch {
      // 忽略单个文件读写/删除失败，避免阻断主线启动
    }
  }
}

export function getOpenHisProjectDir(webEleDir: string): string | null {
  const projectId = resolveOpenHisProjectId();
  if (!projectId) {
    return null;
  }

  const monorepoRoot = path.resolve(webEleDir, '../..');
  const projectDir = path.join(monorepoRoot, 'projects', `project-${projectId}`);
  return fs.existsSync(projectDir) ? projectDir : null;
}

/**
 * 院点模式：在 Vite 进程内用 UTF-8 读取 projects/project-{id} 下的 env 文件，写入 process.env。
 * 避免依赖 apps/web-ele 下 env.local 残留（会污染主线），也避免 Windows 传中文 env 乱码
 * 导致刷新后标题回退成 OpenHis。
 * 注意：块注释内禁止出现星号紧挨斜杠的 glob 写法，否则会提前结束注释。
 */
export function hydrateOpenHisProjectEnv(webEleDir: string): void {
  const projectDir = getOpenHisProjectDir(webEleDir);
  const projectId = resolveOpenHisProjectId();
  if (!projectDir || !projectId) {
    return;
  }

  const mode = detectViteModeFromArgv();
  const files = ['.env', `.env.${mode}`, '.env.local', `.env.${mode}.local`];
  const merged: Record<string, string> = {};
  for (const file of files) {
    const filePath = path.join(projectDir, file);
    if (!fs.existsSync(filePath)) {
      continue;
    }
    Object.assign(merged, parseEnvFileContent(fs.readFileSync(filePath, 'utf8')));
  }

  if (Object.keys(merged).length === 0) {
    return;
  }

  Object.assign(process.env, merged);
  process.env.OPENHIS_PROJECT = projectId;
  process.env.VITE_OPENHIS_PROJECT = projectId;
  console.log(
    `[openhis-project] hydrated env from project-${projectId} (${Object.keys(merged).length} keys, mode=${mode})`,
  );
}

function walkOverrideFiles(dir: string, relativeBase = ''): Array<{ abs: string; rel: string }> {
  if (!fs.existsSync(dir)) {
    return [];
  }

  const files: Array<{ abs: string; rel: string }> = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = relativeBase ? `${relativeBase}/${entry.name}` : entry.name;
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkOverrideFiles(abs, rel));
      continue;
    }
    if (entry.isFile()) {
      files.push({ rel, abs });
    }
  }
  return files;
}

function isUnderDir(filePath: string, dirNormalizedLower: string): boolean {
  return path.normalize(filePath).toLowerCase().startsWith(dirNormalizedLower);
}

/**
 * 编译期重载：overrides/ 下存在同名 #/ 模块时优先使用。
 *
 * 硬约束：
 * 1. 必须剥离 ?vue&type=* 再找文件，再把 query 拼回（否则 script/style 二次 resolve 会错文件、scoped hash 不一致）。
 * 2. 主线 importer 的 #/ 未命中 override 时必须 return null，交给 package.json imports。
 *    若强行返回 src 绝对路径，Vite 生产构建会丢掉该 SFC 的 scoped CSS
 *    （StationTriPaneLayout 左右栏、患者信息卡等表现为布局/样式丢失）。
 * 3. 仅当 importer 位于 projects 院点 overrides 目录内时，才把未覆盖的 #/ 回退解析到 src（包外无法走 imports）。
 */
export function createOpenHisProjectOverridePlugin(webEleDir: string): Plugin | null {
  const projectDir = getOpenHisProjectDir(webEleDir);
  if (!projectDir) {
    return null;
  }

  const projectId = resolveOpenHisProjectId()!;
  const monorepoRoot = path.resolve(webEleDir, '../..');
  const overridesDir = path.join(projectDir, 'overrides');
  const hasOverrides = fs.existsSync(overridesDir);
  const overrideCount = hasOverrides ? walkOverrideFiles(overridesDir).length : 0;
  const srcDir = path.join(webEleDir, 'src');
  const projectDirNormalized = path.normalize(projectDir).toLowerCase();
  const srcDirNormalized = path.normalize(srcDir).toLowerCase();

  return {
    name: 'openhis-project-override',
    enforce: 'pre',
    config() {
      console.log(
        `[openhis-project] project-${projectId}${hasOverrides ? ` (overrides: ${overrideCount})` : ' (env only)'}`,
      );
      return {
        server: {
          fs: {
            allow: [monorepoRoot],
          },
        },
      };
    },
    async resolveId(source, importer, options) {
      if (source.startsWith('\0')) {
        return null;
      }

      const { id: bareId, query } = splitQuery(source);
      const importerPath = importer?.split('?')[0] ?? '';
      const importerFromProject =
        Boolean(importerPath) && isUnderDir(importerPath, projectDirNormalized);

      // 1) #/ 别名
      if (bareId.startsWith('#/')) {
        const rel = bareId.slice(2).replace(/\\/g, '/');

        if (hasOverrides) {
          const overrideFile = resolveExistingFile(path.join(overridesDir, rel));
          if (overrideFile) {
            return overrideFile + query;
          }
        }

        // overrides 内 import 主线模块：包外无 imports 映射，需显式回退 src
        if (importerFromProject) {
          const srcFile = resolveExistingFile(path.join(srcDir, rel));
          if (srcFile) {
            return srcFile + query;
          }
        }

        // 主线 importer：不拦截，走 package.json "#/*" → ./src/*，保留生产 CSS 链接
        return null;
      }

      // 2) 已落到主线 src 的绝对路径 → 若有同名 override 则改道（覆盖 imports 抢先映射）
      // 注意：不得改道 type=style/template 子请求。主线 scoped hash 与 override（尤其是样式已抽到 .css）
      // 不一致时，把 style 指到 override 会导致把整份 .vue 当 CSS 解析（Unknown word <script>）。
      if (
        hasOverrides &&
        path.isAbsolute(bareId) &&
        isUnderDir(bareId, srcDirNormalized) &&
        !query.includes('type=style') &&
        !query.includes('type=template')
      ) {
        const rel = path.relative(srcDir, bareId).replace(/\\/g, '/');
        if (rel && !rel.startsWith('..')) {
          const overrideFile = resolveExistingFile(path.join(overridesDir, rel));
          if (overrideFile) {
            return overrideFile + query;
          }
        }
      }

      // 3) overrides 发起的 bare import：按 web-ele 依赖树解析
      if (importerFromProject && isBarePackageImport(source)) {
        const resolved = await this.resolve(source, path.join(webEleDir, 'package.json'), {
          ...options,
          skipSelf: true,
        });
        return resolved;
      }

      return null;
    },
  };
}
