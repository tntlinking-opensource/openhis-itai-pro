#!/usr/bin/env node
/**
 * 带院点 env 启动 web-ele 构建/开发。
 *
 * 用法：
 *   ZXPLAT_PROJECT=H22010402403 node scripts/zxplat-project/run-web-ele.mjs -- pnpm vite build --mode production
 *   node scripts/zxplat-project/run-web-ele.mjs --project H22010402403 -- pnpm vite --mode development
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const uiRoot = resolve(__dirname, '../..');
const webEleDir = join(uiRoot, 'apps/web-ele');

/** 与 vite.project-override-plugin.ts 中 ZXPLAT_PROJECT_LOCAL_ENV_MARKER 保持一致 */
const LOCAL_ENV_MARKER = 'auto-generated by zxplat-project/run-web-ele.mjs';

/**
 * 院点 overlay：优先本仓 `projects/project-{id}/`；
 * 兼容旧主仓路径 `…/projects/project-{id}/ui`。
 */
function resolveProjectDir(projectId) {
  const localDir = join(uiRoot, 'projects', `project-${projectId}`);
  if (existsSync(localDir)) {
    return localDir;
  }
  const fromEnv = (process.env.ZXPLAT_ROOT ?? '').trim();
  const legacy = [
    fromEnv ? join(resolve(fromEnv), 'projects', `project-${projectId}`, 'ui') : '',
    join(uiRoot, '../zxplat/projects', `project-${projectId}`, 'ui'),
    join(uiRoot, '..', 'projects', `project-${projectId}`, 'ui'),
  ].filter(Boolean);
  for (const candidate of legacy) {
    if (existsSync(candidate)) {
      return candidate;
    }
  }
  return localDir;
}

/** 本次写入的 apps/web-ele/.env.*.local，进程结束时删除，避免污染主线 */
let syncedLocalEnvPath = '';

function parseEnvFile(content) {
  const env = {};
  for (const line of content.split(/\r?\n/u)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }
    const idx = trimmed.indexOf('=');
    if (idx < 1) {
      continue;
    }
    env[trimmed.slice(0, idx).trim()] = trimmed.slice(idx + 1).trim();
  }
  return env;
}

function normalizeProjectId(value) {
  const raw = String(value ?? '').trim();
  if (!raw) {
    return '';
  }
  return raw.startsWith('project-') ? raw.slice('project-'.length) : raw;
}

function parseArgs(argv) {
  let project = normalizeProjectId(process.env.ZXPLAT_PROJECT);
  const command = [];

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--project' && argv[i + 1]) {
      project = normalizeProjectId(argv[i + 1]);
      i += 1;
      continue;
    }
    if (arg === '--') {
      command.push(...argv.slice(i + 1));
      break;
    }
    command.push(arg);
  }

  return { project, command };
}

function detectMode(command) {
  const modeIndex = command.indexOf('--mode');
  if (modeIndex >= 0 && command[modeIndex + 1]) {
    return command[modeIndex + 1];
  }
  if (command.some((item) => item.includes('development'))) {
    return 'development';
  }
  return 'production';
}

function normalizeCommand(command) {
  if (command.length >= 2 && command[0] === 'pnpm' && command[1] === 'vite') {
    return ['pnpm', 'exec', 'vite', ...command.slice(2)];
  }

  return command;
}

function usesShell(command) {
  if (process.platform !== 'win32') {
    return false;
  }

  const executable = (command[0] ?? '').toLowerCase();
  // Windows 下 pnpm/npm 多为 .cmd/.ps1 包装，无 shell 时 spawnSync 会 ENOENT
  return (
    /\.(cmd|bat|ps1)$/i.test(executable) ||
    executable === 'pnpm' ||
    executable === 'npm' ||
    executable === 'npx' ||
    executable === 'yarn'
  );
}

function quoteForShell(value) {
  return /[\s"]/u.test(value) ? `"${value.replace(/"/g, '\\"')}"` : value;
}

function spawnCommand(command, options) {
  if (usesShell(command)) {
    const commandLine = command.map(quoteForShell).join(' ');
    return spawnSync(commandLine, {
      ...options,
      shell: true,
    });
  }

  return spawnSync(command[0], command.slice(1), {
    ...options,
    shell: false,
  });
}

function forwardSpawnOutput(result) {
  if (result.stdout?.length) {
    process.stdout.write(result.stdout);
  }
  if (result.stderr?.length) {
    process.stderr.write(result.stderr);
  }
}

function loadProjectEnv(projectId, mode) {
  const projectDir = resolveProjectDir(projectId);
  if (!existsSync(projectDir)) {
    console.warn(`[zxplat-project] missing ${projectDir}, skip project env`);
    console.warn(
      '[zxplat-project] hint: place overlay at zxplat-ui/projects/project-{id}/',
    );
    return;
  }

  // 合并院点 env，并临时写入 web-ele/.env.{mode}.local（UTF-8）。
  // vite-plugin-html / import.meta.env 需要该文件才能稳定显示中文品牌名；
  // 主线启动会 purge 残留；本进程退出时也会删掉。
  const files = ['.env', `.env.${mode}`, '.env.local', `.env.${mode}.local`];
  const merged = {};
  for (const file of files) {
    const filePath = join(projectDir, file);
    if (!existsSync(filePath)) {
      continue;
    }
    const parsed = parseEnvFile(readFileSync(filePath, 'utf8'));
    Object.assign(merged, parsed);
    console.log(`[zxplat-project] loaded ${filePath}`);
  }

  if (Object.keys(merged).length === 0) {
    return;
  }

  const localEnvPath = join(webEleDir, `.env.${mode}.local`);
  const lines = [
    `# auto-generated by zxplat-project/run-web-ele.mjs — do not edit`,
    `# source: projects/project-${projectId}`,
    ...Object.entries(merged).map(([key, value]) => `${key}=${value}`),
    '',
  ];
  writeFileSync(localEnvPath, lines.join('\n'), 'utf8');
  syncedLocalEnvPath = localEnvPath;
  console.log(`[zxplat-project] synced ${localEnvPath}`);
}

function cleanupSyncedLocalEnv() {
  if (!syncedLocalEnvPath || !existsSync(syncedLocalEnvPath)) {
    return;
  }
  try {
    const content = readFileSync(syncedLocalEnvPath, 'utf8');
    if (!content.includes(LOCAL_ENV_MARKER)) {
      return;
    }
    unlinkSync(syncedLocalEnvPath);
    console.log(`[zxplat-project] cleaned ${syncedLocalEnvPath}`);
  } catch (error) {
    console.warn(
      `[zxplat-project] failed to clean ${syncedLocalEnvPath}: ${error?.message ?? error}`,
    );
  } finally {
    syncedLocalEnvPath = '';
  }
}

const { project, command } = parseArgs(process.argv.slice(2));
if (!command.length) {
  console.error(
    'Usage: node scripts/zxplat-project/run-web-ele.mjs [--project ID] -- <command...>',
  );
  process.exit(1);
}

// 本脚本专供院点构建/开发。未指定院点时若继续跑 Vite，会静默打出产品主线包，
// overrides（如院点中药处方壳）不会进入产物，表现为「组件没打进去」。
if (!project) {
  console.error(
    '[zxplat-project] missing ZXPLAT_PROJECT (or --project). Refusing to continue.',
  );
  console.error(
    '  PowerShell:  $env:ZXPLAT_PROJECT = \"H22010402403\"; pnpm run build:ele:project',
  );
  console.error(
    '  Or:          node scripts/zxplat-project/run-web-ele.mjs --project H22010402403 -- pnpm vite build --mode production',
  );
  process.exit(1);
}

process.env.ZXPLAT_PROJECT = project;
process.env.VITE_ZXPLAT_PROJECT = project;
loadProjectEnv(project, detectMode(command));
console.log(`[zxplat-project] ZXPLAT_PROJECT=${project}`);

process.on('exit', cleanupSyncedLocalEnv);
for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => {
    cleanupSyncedLocalEnv();
    process.exit(signal === 'SIGINT' ? 130 : 143);
  });
}

const normalizedCommand = normalizeCommand(command);
const usePipe =
  !process.stdout.isTTY ||
  !process.stderr.isTTY ||
  process.env.WHALEOPS_PACK === '1';
const result = spawnCommand(normalizedCommand, {
  cwd: webEleDir,
  stdio: usePipe ? 'pipe' : 'inherit',
  env: process.env,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});

if (usePipe) {
  forwardSpawnOutput(result);
}

cleanupSyncedLocalEnv();

if (result.error) {
  console.error(`[zxplat-project] spawn failed: ${result.error.message}`);
  process.exit(1);
}

process.exit(result.status ?? 1);
